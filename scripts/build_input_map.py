# プレースホルダ（"?" を含む候補）は無効として除去するためのマーカー
def is_valid_ref(ref: str) -> bool:
    return "?" not in ref


def main():
    items = pd.read_csv(os.path.join(DATA, "items.csv"), encoding="utf-8-sig")
    it = items[items["level"] == "品目"]
    dom = it[it["kind"] == "domestic"].copy()
    imp = it[it["kind"] == "import_yen"].copy()

    dom["group"] = dom["group_path"].str.split(">").str[-1]

    # 名前→コードの辞書（重複名はリスト保持し、参照時にエラーにする）
    def name_index(df):
        idx = {}
        for _, r in df.iterrows():
            idx.setdefault(r["name"], []).append(r["code"])
        return idx

    dom_idx = name_index(dom)
    imp_idx = name_index(imp)

    def resolve(ref):
        src, name = ref.split(":", 1)
        idx = dom_idx if src == "D" else imp_idx
        if name not in idx:
            return None, f"未解決: {ref}"
        if len(idx[name]) > 1:
            return None, f"名前が曖昧: {ref} -> {idx[name]}"
        return idx[name][0], None

    rows, problems = [], []
    code2name = dict(zip(items["code"], items["name"]))

    for _, r in dom.iterrows():
        name, group, tcode = r["name"], r["group"], r["code"]
        rule = ITEM_RULES.get(name) or GROUP_RULES.get(group)
        if rule is None:
            problems.append(f"ルールなし: {group} / {name}")
            continue
        used = set()
        for ref, reason in rule:
            if not is_valid_ref(ref):
                continue
            ccode, err = resolve(ref)
            if err:
                problems.append(f"{name}: {err}")
                continue
            if ccode == tcode or ccode in used:  # 自己参照・重複は除外
                continue
            used.add(ccode)
            rows.append({
                "対象品目コード": tcode,
                "対象品目名": name,
                "候補品目コード": ccode,
                "候補品目名": code2name[ccode],
                "根拠": reason,
            })

    out = pd.DataFrame(rows)

    # 一方向性チェック：逆向きペアが存在したら後勝ちの方を削除
    pairs = set(zip(out["対象品目コード"], out["候補品目コード"]))
    reverse = [(a, b) for (a, b) in pairs if (b, a) in pairs]
    if reverse:
        # コード昇順で「上流→下流」と見なし、下流→上流側を残すペアを削除
        drop = set()
        for a, b in reverse:
            drop.add((max(a, b), min(a, b)))
        before = len(out)
        out = out[~out.apply(lambda r: (r["対象品目コード"], r["候補品目コード"]) in drop, axis=1)]
        problems.append(f"双方向ペア {len(drop)} 組を検出し片方向を削除（{before}->{len(out)}行）")

    # 候補数の集計
    cnt = out.groupby("対象品目コード").size()
    print(f"対象品目数: {out['対象品目コード'].nunique()} / {len(dom)}")
    print(f"候補数 min={cnt.min()} max={cnt.max()} mean={cnt.mean():.1f}")
    few = cnt[cnt < 3]
    if len(few):
        print(f"候補3未満の品目: {len(few)}件")

    out.to_csv(os.path.join(DATA, "input_map.csv"), index=False, encoding="utf-8-sig")
    print(f"data/input_map.csv 書き出し: {len(out)}行")

    if problems:
        print("\n--- 要確認 ---")
        for p in sorted(set(problems)):
            print(" ", p)
        sys.exit(1 if any("ルールなし" in p or "未解決" in p for p in problems) else 0)


