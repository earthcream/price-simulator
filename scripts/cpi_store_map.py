def classify(name, path):
    """name: 品目名, path: 上位分類名を'>'で連結した文字列（品目自身は含まない）"""
    if not path:
        return "分析用の合成系列"
    for kws, store in NAME_RULES:
        if any(k in name for k in kws):
            return store
    for prefix, store in PATH_RULES:
        if path.startswith(prefix):
            return store
    return "分析用の合成系列"
